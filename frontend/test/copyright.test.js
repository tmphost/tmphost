import { describe, expect, it, vi } from 'vitest'
import {
  NOTICE_LINES,
  carriesNotice,
  check,
  extensionOf,
  isOurs,
  kindOf,
  noticeFor,
  report,
  withNotice,
} from '../scripts/copyright.js'

const GO = NOTICE_LINES.map((line) => `// ${line}`).join('\n')
const HASH = NOTICE_LINES.map((line) => `# ${line}`).join('\n')
const MARKUP = `<!--\n${NOTICE_LINES.map((l) => `  ${l}`).join('\n')}\n-->`

describe('extensionOf', () => {
  it('reads the extension of the file, not of a directory', () => {
    expect(extensionOf('a/b.go')).toBe('.go')
    expect(extensionOf('a.d/Makefile')).toBe('')
    expect(extensionOf(undefined)).toBe('')
  })
})

describe('kindOf', () => {
  it('keys Dockerfile and Makefile by name, everything else by extension', () => {
    expect(kindOf('Dockerfile')).toBe('Dockerfile')
    expect(kindOf('cli/Makefile')).toBe('Makefile')
    expect(kindOf('a/install.sh')).toBe('.sh')
    expect(kindOf('Dockerfile.dev')).toBe('.dev')
    expect(kindOf(undefined)).toBe('')
  })
})

describe('isOurs', () => {
  it('marks source files only', () => {
    expect(isOurs('backend/main.go')).toBe(true)
    expect(isOurs('frontend/src/App.vue')).toBe(true)
    expect(isOurs('frontend/src/style.css')).toBe(true)
    expect(isOurs('frontend/index.html')).toBe(true)
    for (const path of ['install.sh', 'install.ps1', '.github/workflows/ci.yml', 'base.yaml', 'Dockerfile', 'Makefile']) {
      expect(isOurs(path)).toBe(true)
    }
    expect(isOurs('go.sum')).toBe(false)
    expect(isOurs('package.json')).toBe(false)
    expect(isOurs('README.md')).toBe(false)
    expect(isOurs(null)).toBe(false)
  })

  it('leaves dependencies and build output alone', () => {
    expect(isOurs('frontend/node_modules/x/index.js')).toBe(false)
    expect(isOurs('frontend/dist/app.js')).toBe(false)
    expect(isOurs('coverage/lcov.js')).toBe(false)
  })
})

describe('noticeFor', () => {
  it('writes the notice in each file kind’s comment syntax', () => {
    expect(noticeFor('a.go')).toBe(GO)
    expect(noticeFor('a.mjs')).toBe(GO)
    expect(noticeFor('a.vue')).toBe(MARKUP)
    expect(noticeFor('index.html')).toBe(MARKUP)
    expect(noticeFor('install.sh')).toBe(HASH)
    expect(noticeFor('Makefile')).toBe(HASH)
    expect(noticeFor('a.css')).toBe(`/*\n${NOTICE_LINES.map((l) => ` * ${l}`).join('\n')}\n */`)
    expect(noticeFor('a.txt')).toBe('')
  })
})

describe('carriesNotice', () => {
  it('accepts the exact block near the top', () => {
    expect(carriesNotice(`${GO}\n\npackage main\n`, 'a.go')).toBe(true)
    expect(carriesNotice(`#!/usr/bin/env node\n${GO}\n`, 'a.js')).toBe(true)
  })

  it('rejects a missing, partial or reworded notice', () => {
    expect(carriesNotice('package main\n', 'a.go')).toBe(false)
    expect(carriesNotice(`// ${NOTICE_LINES[0]}\n\npackage main\n`, 'a.go')).toBe(false)
    expect(carriesNotice(GO.replace('2026', '2025'), 'a.go')).toBe(false)
    expect(carriesNotice(undefined, 'a.go')).toBe(false)
  })

  it('rejects a notice buried below the first lines', () => {
    expect(carriesNotice(`${'\n'.repeat(8)}${GO}`, 'a.go')).toBe(false)
  })

  it('needs none on other files or generated code', () => {
    expect(carriesNotice('', 'README.md')).toBe(true)
    expect(carriesNotice('// Code generated by MockGen. DO NOT EDIT.\npackage mocks\n', 'mocks/a.go')).toBe(true)
  })
})

describe('withNotice', () => {
  it('prepends the notice and a blank line', () => {
    expect(withNotice('package main\n', 'a.go')).toBe(`${GO}\n\npackage main\n`)
    expect(withNotice(undefined, 'a.go')).toBe(`${GO}\n\n`)
  })

  it('keeps a shebang or doctype on the first line', () => {
    expect(withNotice('#!/bin/sh\necho hi\n', 'install.sh')).toBe(`#!/bin/sh\n${HASH}\n\necho hi\n`)
    expect(withNotice('#!/bin/sh', 'install.sh')).toBe(`#!/bin/sh\n${HASH}\n`)
    expect(withNotice('<!DOCTYPE html>\n<html>\n', 'index.html')).toBe(`<!DOCTYPE html>\n${MARKUP}\n\n<html>\n`)
  })

  it('puts it above an ordinary first comment', () => {
    expect(withNotice('# Builds it.\nFROM x\n', 'Dockerfile')).toBe(`${HASH}\n\n# Builds it.\nFROM x\n`)
  })

  it('leaves a file that has it unchanged', () => {
    const text = `${GO}\n\npackage main\n`
    expect(withNotice(text, 'a.go')).toBe(text)
  })
})

describe('check', () => {
  const contents = { 'ok.go': `${GO}\n`, 'bad.go': 'package main\n', 'README.md': '' }
  const read = (path) => contents[path]

  it('names the files missing the notice', () => {
    const write = vi.fn()
    expect(check(Object.keys(contents), { read, write })).toEqual({ files: ['ok.go', 'bad.go'], missing: ['bad.go'] })
    expect(write).not.toHaveBeenCalled()
  })

  it('adds the notice with fix', () => {
    const write = vi.fn()
    expect(check(Object.keys(contents), { read, write, fix: true }).missing).toEqual([])
    expect(write).toHaveBeenCalledOnce()
    expect(write).toHaveBeenCalledWith('bad.go', `${GO}\n\npackage main\n`)
  })
})

describe('report', () => {
  it('names one file and the expected notice', () => {
    const text = report(['a.go'])
    expect(text).toContain('✗ 1 file without')
    expect(text).toContain('    a.go')
    expect(text).toContain(`    ${NOTICE_LINES[2]}`)
    expect(text).toContain('--fix')
  })

  it('truncates a long list', () => {
    const text = report(['a.go', 'b.go', 'c.go'], 2)
    expect(text).toContain('✗ 3 files without')
    expect(text).not.toContain('c.go')
    expect(text).toContain('… and 1 more')
  })
})
